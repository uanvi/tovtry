import { copyFile, mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.resolve(process.argv[2] || path.join(root, 'img', 'pngframes'));
const destination = path.join(root, 'assets', 'frames', 'hero');
const frames = (await readdir(source, { withFileTypes: true }))
  .filter(entry => entry.isFile() && /^frame_\d+\.avif$/i.test(entry.name))
  .map(entry => entry.name)
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
if (frames.length < 2) throw new Error(`Expected at least two AVIF frames in ${source}`);

await mkdir(destination, { recursive: true });
let bytes = 0;
for (const name of frames) {
  await copyFile(path.join(source, name), path.join(destination, name));
  bytes += (await stat(path.join(destination, name))).size;
}
// Explicit filenames preserve source numbering gaps without requesting missing files.
await writeFile(path.join(destination, 'sequence.js'),
  `// Generated by npm run prepare-hero. Filenames are in playback order.\nexport const heroFrames = ${JSON.stringify(frames, null, 2)};\n`);
console.log(`Hero: ${frames.length} AVIF frames, ${(bytes / 1024 ** 2).toFixed(2)} MiB, ${frames[0]} -> ${frames.at(-1)}`);
